# bin_generator.py
#
# Regenerates the static bin_types list in bin_types.py from the BED-BPP
# dataset. Run this directly whenever the dataset or cost formula changes:
#
#     python bin_generator.py
#
# It writes bin_types.py itself (see write_bin_types_file below), so the two
# files can no longer drift out of sync with each other.

import json
import pprint

import numpy as np
import pandas as pd
from sklearn.cluster import KMeans


def compute_bin_types(dataset_path="bed-bpp_v1.json"):
    print("Loading dataset...")
    with open(dataset_path, "r") as f:
        bed_bpp_data = json.load(f)

    items_data = []
    for order in bed_bpp_data.values():
        for item in order["item_sequence"].values():
            items_data.append([
                item["length/mm"], item["width/mm"], item["height/mm"], item["weight/kg"]
            ])

    df = pd.DataFrame(items_data, columns=["length", "width", "height", "weight"])

    print("Running K-Means clustering (k=4)...")
    kmeans = KMeans(n_clusters=4, random_state=42, n_init=10)
    df["cluster"] = kmeans.fit_predict(df[["length", "width", "height"]])

    bins = df.groupby("cluster").max().reset_index()
    bins["volume"] = bins["length"] * bins["width"] * bins["height"]
    bins = bins.sort_values("volume").reset_index(drop=True)
    bins["bin_name"] = ["Small", "Medium", "Large", "Extra Large"]

    # W, H, D are the dimensions of the largest (reference) bin.
    # cost = ceil(1000 * (1.2*V_k - 0.2*WHD) / WHD) -- adapted from
    # Alvarez-Valdes et al. (2013), after Pisinger & Sigurd (2005).
    largest_bin = bins.loc[bins["volume"].idxmax()]
    WHD = largest_bin["length"] * largest_bin["width"] * largest_bin["height"]
    bins["cost"] = np.ceil(1000 * (1.2 * bins["volume"] - 0.2 * WHD) / WHD).astype(int)

    bin_types = []
    for _, row in bins.iterrows():
        bin_types.append({
            "name": row["bin_name"].lower().replace(" ", "_"),
            "length": int(row["length"] * 1.05),
            "width": int(row["width"] * 1.05),
            "height": int(row["height"] * 1.05),
            "cost": int(row["cost"]),
            "max_weight": int(row["weight"] * 1.05),
        })

    return bin_types, df, bins


def plot_clusters(df, bins, save_path="cluster_visualization.png", show=True):
    import matplotlib.pyplot as plt

    print("Generating 3D visualization of the clusters...")
    fig = plt.figure(figsize=(10, 8))
    ax = fig.add_subplot(111, projection="3d")

    for _, row in bins.iterrows():
        cluster_items = df[df["cluster"] == row["cluster"]]
        ax.scatter(cluster_items["length"], cluster_items["width"], cluster_items["height"],
                   label=f"{row['bin_name']} Items", alpha=0.4)
        ax.scatter(row["length"], row["width"], row["height"],
                   c="red", marker="*", s=300, edgecolor="black")
        ax.text(row["length"], row["width"], row["height"] + 40,
                row["bin_name"], size=11, zorder=1, color="black", fontweight="bold")

    ax.set_title("K-Means Clustering of BED-BPP Grocery Items")
    ax.set_xlabel("Length (mm)")
    ax.set_ylabel("Width (mm)")
    ax.set_zlabel("Height (mm)")
    ax.scatter([], [], [], c="red", marker="*", s=200, edgecolor="black", label="Max Box Dimensions")
    ax.legend()

    if save_path:
        plt.savefig(save_path, dpi=300, bbox_inches="tight")
    if show:
        plt.show()


def write_bin_types_file(bin_types, path="bin_types.py"):
    """Writes bin_types.py as static data + the Bin class -- deliberately NOT
    importable side effects. Nothing in this project should re-run clustering
    just from `import bin_types`."""
    with open(path, "w", newline="\r\n") as f:
        f.write('# bin_types.py\n\n\n')
        f.write('"""\n')
        f.write("Bin type definitions and Bin class for 3D bin packing.\n\n")
        f.write("bin_types below is generated by bin_generator.py -- run that\n")
        f.write("script directly to regenerate this file if the dataset or\n")
        f.write('cost formula changes:\n\n')
        f.write("    python bin_generator.py\n")
        f.write('"""\n\n')
        f.write("#\n# BIN TYPES\n#\n\n")
        f.write("bin_types = \\\n")
        f.write(pprint.pformat(bin_types, sort_dicts=False))
        f.write("\n\n\n#\n# BIN CLASS\n#\n\n")
        f.write('class Bin:\n')
        f.write('    """\n')
        f.write("    Represents a bin's dimensions and its available Empty Maximal Spaces (EMS)\n")
        f.write('    """\n')
        f.write("    def __init__(self, bin_type):\n")
        f.write('        self.name = bin_type["name"]\n')
        f.write('        self.length = bin_type["length"]\n')
        f.write('        self.width = bin_type["width"]\n')
        f.write('        self.height = bin_type["height"]\n')
        f.write('        self.cost = bin_type["cost"]\n\n')
        f.write("        # The first ems is the entire bin space\n")
        f.write("        self.ems_list = [(0, 0, 0, self.length, self.width, self.height)]\n\n")
        f.write("        # Keeping track of items placed inside\n")
        f.write("        self.placed_items = []\n\n")
        f.write("    def __repr__(self):\n")
        f.write('        return f"Bin({self.name}, EMSs: {len(self.ems_list)}, Items: {len(self.placed_items)})"\n')
    print(f"bin_types.py written to {path}")


if __name__ == "__main__":
    bin_types, df, bins = compute_bin_types()

    print("\n=== bin_types ===")
    pprint.pprint(bin_types, sort_dicts=False)

    write_bin_types_file(bin_types, path="bin_types.py")

    os_makedirs_ok = True
    try:
        import os
        os.makedirs("Visuals", exist_ok=True)
        plot_clusters(df, bins, save_path="Visuals/cluster_visualization.png", show=False)
    except Exception as e:
        print(f"(Skipped cluster plot: {e})")
